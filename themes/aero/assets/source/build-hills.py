#!/usr/bin/env python3
"""M · Rolling hills (www#251, greenery variants of H): builds hills.svg and
meadow.svg. Original vector art, generated by this script on 2026-11-28. No
third-party art, no tracing, no brand marks. Both tiles repeat on x (every
ridge is a sum of whole-period waves). Run: python3 -I build-hills.py
"""
import math
import os
import random

OUT = os.path.dirname(os.path.abspath(__file__))


def svg(name, w, h, body, defs=""):
    doc = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">\n'
        f"<!-- M Rolling hills: {name}. Original vector art for this rendition. -->\n"
        f"<defs>{defs}</defs>\n{body}\n</svg>\n"
    )
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write(doc)


def f(x):
    return f"{x:.1f}".rstrip("0").rstrip(".")


def ridge(w, base, waves):
    """A periodic crest line: base minus whole-period cosine bumps."""
    def y(x):
        return base - sum(a * (0.5 + 0.5 * math.cos(2 * math.pi * k * x / w + p)) for a, k, p in waves)
    return y


def fill_path(w, h, y, step=6):
    pts = " ".join(f"L{f(x)} {f(y(x))}" for x in range(0, w + step, step))
    return f"M0 {h} L0 {f(y(0))} {pts} L{w} {h}Z"


def crest_path(w, y, x0, x1, step=6):
    pts = [f"{f(x)} {f(y(x))}" for x in range(int(x0), int(x1), step)]
    return "M" + " L".join(pts)


GLOW = ('<radialGradient id="glow"><stop offset="0" stop-color="#ffffff" stop-opacity="0.95"/>'
        '<stop offset="0.35" stop-color="#f4ffe8" stop-opacity="0.5"/>'
        '<stop offset="1" stop-color="#e0ffd0" stop-opacity="0"/></radialGradient>')

TREES = """
<radialGradient id="canopy" cx="0.34" cy="0.28" r="0.78"><stop offset="0" stop-color="#d4ff8a"/><stop offset="0.45" stop-color="#5cc83a"/><stop offset="1" stop-color="#1c7a2e"/></radialGradient>
<radialGradient id="canopyd" cx="0.34" cy="0.28" r="0.78"><stop offset="0" stop-color="#a8ec6a"/><stop offset="0.55" stop-color="#34a03a"/><stop offset="1" stop-color="#15602c"/></radialGradient>
<radialGradient id="canopyf" cx="0.34" cy="0.28" r="0.78"><stop offset="0" stop-color="#d8f6d0"/><stop offset="0.6" stop-color="#8fcfa6"/><stop offset="1" stop-color="#5fa98c"/></radialGradient>
<linearGradient id="trunk" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#a77a4e"/><stop offset="1" stop-color="#5e3d22"/></linearGradient>
"""


def tree(rnd, x, base, r, grad="canopy"):
    """A round glossy tree: trunk, three-lobed crown, a lit cap and a glint."""
    s = f'<rect x="{f(x - r*0.09)}" y="{f(base - r*0.9)}" width="{f(r*0.18)}" height="{f(r*0.9)}" rx="{f(r*0.06)}" fill="url(#trunk)"/>'
    cy = base - r * 1.45
    for dx, dy, rr in ((-0.45, 0.2, 0.62), (0.45, 0.22, 0.6), (0, -0.15, 0.8)):
        s += f'<circle cx="{f(x + dx*r)}" cy="{f(cy + dy*r)}" r="{f(rr*r)}" fill="url(#{grad})"/>'
    s += (f'<ellipse cx="{f(x - r*0.22)}" cy="{f(cy - r*0.5)}" rx="{f(r*0.34)}" ry="{f(r*0.18)}" fill="#ffffff" opacity="0.42"/>'
          f'<circle cx="{f(x - r*0.4)}" cy="{f(cy - r*0.52)}" r="{f(max(1, r*0.07))}" fill="#ffffff" opacity="0.9"/>')
    return s


def poplar(x, base, r, grad="canopyd"):
    """A tall oval tree (cypress / poplar), upright."""
    return (f'<rect x="{f(x - r*0.08)}" y="{f(base - r*0.7)}" width="{f(r*0.16)}" height="{f(r*0.7)}" fill="url(#trunk)"/>'
            f'<ellipse cx="{f(x)}" cy="{f(base - r*1.9)}" rx="{f(r*0.48)}" ry="{f(r*1.45)}" fill="url(#{grad})"/>'
            f'<ellipse cx="{f(x - r*0.16)}" cy="{f(base - r*2.6)}" rx="{f(r*0.14)}" ry="{f(r*0.45)}" fill="#ffffff" opacity="0.38"/>')


def cluster(rnd, x, y, r, grad, n):
    s = ""
    items = sorted(((x + rnd.uniform(-1.6, 1.6) * r, rnd.uniform(0.7, 1.15) * r, rnd.random() < 0.3) for _ in range(n)),
                   key=lambda t: t[1])
    for tx, tr, tall in items:
        base = y(tx) + tr * 0.35 if callable(y) else y
        s += poplar(tx, base, tr * 0.8, grad) if tall else tree(rnd, tx, base, tr, grad)
    return s


def butterfly(x, y, s, hue_a, hue_b, gid):
    """An upright butterfly, wings open, gradient wings with a white glint."""
    g = (f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{hue_a}"/>'
         f'<stop offset="1" stop-color="{hue_b}"/></linearGradient>')
    body = (f'<g transform="translate({f(x)} {f(y)}) scale({s})">'
            '<path d="M0 0 C-4 -10 -15 -13 -17 -6 C-18 0 -10 3 0 2Z" fill="url(#G)" stroke="#ffffff" stroke-width="0.8" stroke-opacity="0.8"/>'
            '<path d="M0 0 C4 -10 15 -13 17 -6 C18 0 10 3 0 2Z" fill="url(#G)" stroke="#ffffff" stroke-width="0.8" stroke-opacity="0.8"/>'
            '<path d="M0 2 C-3 6 -10 10 -11 6 C-12 3 -6 2 0 2Z" fill="url(#G)" opacity="0.92"/>'
            '<path d="M0 2 C3 6 10 10 11 6 C12 3 6 2 0 2Z" fill="url(#G)" opacity="0.92"/>'
            '<ellipse cx="-9" cy="-7" rx="3.2" ry="1.6" fill="#ffffff" opacity="0.7"/>'
            '<ellipse cx="9" cy="-7" rx="3.2" ry="1.6" fill="#ffffff" opacity="0.7"/>'
            '<rect x="-0.9" y="-5" width="1.8" height="10" rx="0.9" fill="#2a3a5a"/>'
            '<path d="M-0.5 -5 Q-3 -10 -4 -11 M0.5 -5 Q3 -10 4 -11" stroke="#2a3a5a" stroke-width="0.6" fill="none"/>'
            '</g>').replace("url(#G)", f"url(#{gid})")
    return g, body


def flower(x, y, r, col):
    s = ""
    for i in range(5):
        a = i * 2 * math.pi / 5 - math.pi / 2
        s += f'<circle cx="{f(x + math.cos(a)*r)}" cy="{f(y + math.sin(a)*r)}" r="{f(r*0.72)}" fill="{col}"/>'
    s += f'<circle cx="{f(x)}" cy="{f(y)}" r="{f(r*0.55)}" fill="#ffd23a"/>'
    s += f'<circle cx="{f(x - r*0.3)}" cy="{f(y - r*0.3)}" r="{f(r*0.25)}" fill="#ffffff" opacity="0.9"/>'
    return s


def hills():
    """Far and mid ranges behind the skyline, with tree clusters."""
    rnd = random.Random(11)
    w, h = 2400, 320
    defs = GLOW + TREES + """
<linearGradient id="far" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#a9dcc4"/><stop offset="0.6" stop-color="#c8ece4"/><stop offset="1" stop-color="#dff6fb"/></linearGradient>
<linearGradient id="mid" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#8ed86a"/><stop offset="0.45" stop-color="#5cbc4a"/><stop offset="1" stop-color="#9ad9b0"/></linearGradient>
<linearGradient id="haze" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#eaf9ff" stop-opacity="0"/><stop offset="1" stop-color="#e2f6ff" stop-opacity="0.85"/></linearGradient>
<filter id="soft" x="-5%" y="-50%" width="110%" height="200%"><feGaussianBlur stdDeviation="2.2"/></filter>
"""
    yf = ridge(w, h - 70, [(120, 3, 0.4), (60, 5, 2.1), (30, 11, 1.0)])
    ym = ridge(w, h - 20, [(110, 4, 2.6), (50, 7, 0.3), (22, 13, 4.0)])
    body = f'<path d="{fill_path(w, h, yf)}" fill="url(#far)"/>'
    # Far crest light and hazy tree dots.
    body += f'<path d="{crest_path(w, yf, 0, w + 1)}" fill="none" stroke="#f2fff6" stroke-width="3" opacity="0.7" filter="url(#soft)"/>'
    for _ in range(26):
        x = rnd.uniform(0, w)
        body += cluster(rnd, x, lambda t: yf(t) + 14, rnd.uniform(5, 8), "canopyf", rnd.randint(2, 4))
    body += f'<rect x="0" y="{h-170}" width="{w}" height="170" fill="url(#haze)"/>'
    # Mid range: bright grass with a lit crest band (the gloss).
    body += f'<path d="{fill_path(w, h, ym)}" fill="url(#mid)"/>'
    body += f'<path d="{crest_path(w, ym, 0, w + 1)}" fill="none" stroke="#e8ffb0" stroke-width="7" opacity="0.65" filter="url(#soft)"/>'
    body += f'<path d="{crest_path(w, ym, 0, w + 1)}" fill="none" stroke="#ffffff" stroke-width="1.6" opacity="0.6"/>'
    # Soft field stripes following the slope.
    for off, op in ((26, 0.18), (52, 0.12)):
        body += f'<path d="{crest_path(w, lambda t: ym(t) + off, 0, w + 1)}" fill="none" stroke="#c9f59a" stroke-width="10" opacity="{op}" filter="url(#soft)"/>'
    for _ in range(16):
        x = rnd.uniform(40, w - 40)
        body += cluster(rnd, x, lambda t: ym(t) + 10, rnd.uniform(9, 15), "canopyd" if rnd.random() < 0.5 else "canopy", rnd.randint(2, 5))
    body += f'<rect x="0" y="{h-110}" width="{w}" height="110" fill="url(#haze)" opacity="0.8"/>'
    svg("hills.svg", w, h, body, defs)


def meadow():
    """A near grassy bank at the waterline, wildflowers, butterflies."""
    rnd = random.Random(23)
    w, h = 1600, 150
    defs = GLOW + TREES + """
<linearGradient id="near" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#b6f06c"/><stop offset="0.4" stop-color="#5fc23c"/><stop offset="1" stop-color="#2f9a3a"/></linearGradient>
<linearGradient id="edge" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#d8f4ff" stop-opacity="0"/><stop offset="1" stop-color="#d8f4ff" stop-opacity="0.9"/></linearGradient>
<filter id="soft" x="-5%" y="-50%" width="110%" height="200%"><feGaussianBlur stdDeviation="2"/></filter>
"""
    yn = ridge(w, h - 6, [(46, 2, 1.2), (26, 5, 3.3), (10, 11, 0.6)])
    body = f'<path d="{fill_path(w, h, yn)}" fill="url(#near)"/>'
    body += f'<path d="{crest_path(w, yn, 0, w + 1)}" fill="none" stroke="#f0ffc0" stroke-width="6" opacity="0.7" filter="url(#soft)"/>'
    body += f'<path d="{crest_path(w, yn, 0, w + 1)}" fill="none" stroke="#ffffff" stroke-width="1.4" opacity="0.75"/>'
    # Grass blades along the crest.
    for x in range(0, w, 5):
        y0 = yn(x) + 3
        hh = rnd.uniform(5, 11)
        lean = rnd.uniform(-3, 3)
        body += f'<path d="M{f(x-1.4)} {f(y0)} Q{f(x+lean*0.4)} {f(y0-hh*0.6)} {f(x+lean)} {f(y0-hh)} Q{f(x+lean*0.2+0.6)} {f(y0-hh*0.5)} {f(x+1.4)} {f(y0)}Z" fill="#8fe05a" opacity="0.9"/>'
    # A few small trees standing on the bank.
    for x in (180, 760, 1290):
        body += cluster(rnd, x, lambda t: yn(t) + 4, rnd.uniform(14, 18), "canopy", rnd.randint(2, 3))
    # Wildflowers, densest near the crest.
    cols = ("#ffffff", "#fff27a", "#ff9ccf", "#a8d8ff", "#ffb8e0")
    for _ in range(170):
        x = rnd.uniform(4, w - 4)
        y = yn(x) + rnd.uniform(4, 40) ** 1.05
        if y > h - 4:
            continue
        body += flower(x, y, rnd.uniform(1.4, 2.6), rnd.choice(cols))
    body += f'<rect x="0" y="{h-30}" width="{w}" height="30" fill="url(#edge)"/>'
    svg("meadow.svg", w, h, body, defs)


def butterflies():
    """A sparse butterfly tile for the air above the hills."""
    rnd = random.Random(7)
    w, h = 1200, 260
    pairs = [("#ffe066", "#ff9a1f"), ("#9fe2ff", "#2f8fe8"), ("#ffc4ec", "#ff6fb4"), ("#ffffff", "#bfe7ff")]
    defs, body = GLOW, ""
    spots = [(140, 70), (420, 160), (610, 40), (880, 120), (1080, 200)]
    for i, (x, y) in enumerate(spots):
        a, b = pairs[i % len(pairs)]
        g, bd = butterfly(x, y, rnd.uniform(0.75, 1.05), a, b, f"bf{i}")
        defs += g
        body += bd
    svg("butterflies.svg", w, h, body, defs)


hills()
meadow()
butterflies()
