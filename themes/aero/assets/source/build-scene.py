def sparkle(x, y, r, op=1.0):
    """A four-point glint with a soft core."""
    k = r * 0.16
    p = (f"M{f(x)} {f(y-r)} Q{f(x+k)} {f(y-k)} {f(x+r)} {f(y)} Q{f(x+k)} {f(y+k)} {f(x)} {f(y+r)} "
         f"Q{f(x-k)} {f(y+k)} {f(x-r)} {f(y)} Q{f(x-k)} {f(y-k)} {f(x)} {f(y-r)}Z")
    return (f'<g opacity="{op:.2f}"><circle cx="{f(x)}" cy="{f(y)}" r="{f(r*0.55)}" fill="url(#glow)"/>'
            f'<path d="{p}" fill="#ffffff"/></g>')


