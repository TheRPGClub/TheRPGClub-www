def tower(rnd, x, base, tw, th, top):
    gid = f"tw{rnd.randint(0, 2)}"
    y = base - th
    s = ""
    if top == "spire":
        s += f'<path d="M{f(x+tw*0.5-1.5)} {f(y-th*0.16)} L{f(x+tw*0.5+1.5)} {f(y-th*0.16)} L{f(x+tw*0.5+3)} {f(y)} L{f(x+tw*0.5-3)} {f(y)}Z" fill="#cfe9fb"/>'
        body = f"M{f(x)} {f(base)} L{f(x)} {f(y+tw*0.4)} L{f(x+tw*0.5)} {f(y)} L{f(x+tw)} {f(y+tw*0.4)} L{f(x+tw)} {f(base)}Z"
    elif top == "round":
        body = f"M{f(x)} {f(base)} L{f(x)} {f(y+tw*0.5)} A{f(tw*0.5)} {f(tw*0.5)} 0 0 1 {f(x+tw)} {f(y+tw*0.5)} L{f(x+tw)} {f(base)}Z"
    elif top == "slant":
        body = f"M{f(x)} {f(base)} L{f(x)} {f(y+tw*0.6)} L{f(x+tw)} {f(y)} L{f(x+tw)} {f(base)}Z"
    else:
        body = f"M{f(x)} {f(base)} L{f(x)} {f(y)} L{f(x+tw)} {f(y)} L{f(x+tw)} {f(base)}Z"
    s += f'<path d="{body}" fill="url(#{gid})"/>'
    s += f'<g clip-path="none"><path d="{body}" fill="url(#twface)"/></g>'
    # Window bands.
    lines = ""
    yy = y + tw * 0.6
    while yy < base - 6:
        lines += f"M{f(x+2)} {f(yy)} H{f(x+tw-2)} "
        yy += rnd.choice((6, 7, 8))
    s += f'<path d="{lines}" stroke="#ffffff" stroke-opacity="0.22" stroke-width="1"/>'
    s += f'<rect x="{f(x+tw*0.12)}" y="{f(y+tw*0.5)}" width="{f(max(2, tw*0.16))}" height="{f(th-tw*0.5)}" fill="#ffffff" opacity="0.55"/>'
    s += f'<path d="{body}" fill="none" stroke="#ffffff" stroke-opacity="0.5" stroke-width="1"/>'
    return s


def treeline(rnd, x0, x1, base, hmin, hmax, dark=False):
    s = ""
    x = x0
    while x < x1:
        r = rnd.uniform(hmin, hmax)
        s += (f'<circle cx="{f(x)}" cy="{f(base - r*0.55)}" r="{f(r)}" fill="url(#{"canopyd" if dark else "canopy"})"/>'
              f'<circle cx="{f(x - r*0.3)}" cy="{f(base - r*0.9)}" r="{f(r*0.3)}" fill="#e6ff9c" opacity="0.35"/>')
        x += r * rnd.uniform(0.9, 1.4)
    return s


