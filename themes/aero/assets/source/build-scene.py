def continents(rnd, n):
    out = ""
    for _ in range(n):
        cx, cy = rnd.uniform(-0.7, 0.7), rnd.uniform(-0.6, 0.7)
        pts = []
        k = rnd.randint(7, 11)
        base = rnd.uniform(0.12, 0.3)
        for i in range(k):
            a = 2 * math.pi * i / k
            r = base * rnd.uniform(0.55, 1.25)
            pts.append((cx + r * math.cos(a) * 1.2, cy + r * math.sin(a)))
        d = f"M{f(pts[0][0]*150)} {f(pts[0][1]*150)} "
        for i in range(k):
            p0, p1 = pts[i], pts[(i + 1) % k]
            mx, my = (p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2
            d += f"Q{f(p0[0]*150)} {f(p0[1]*150)} {f(mx*150)} {f(my*150)} "
        out += f'<path d="{d}Z"/>'
    return out


