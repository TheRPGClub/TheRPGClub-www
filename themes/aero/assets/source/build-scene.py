def waves():
    """Wii-menu fog ribbons: wide, soft, white to pale blue, periodic in x."""
    rnd = random.Random(66)
    w, h = 2400, 900
    defs = """
<filter id="fog" x="-5%" y="-40%" width="110%" height="180%"><feGaussianBlur stdDeviation="16"/></filter>
<filter id="fog2" x="-5%" y="-40%" width="110%" height="180%"><feGaussianBlur stdDeviation="5"/></filter>
<filter id="fog3" x="-5%" y="-40%" width="110%" height="180%"><feGaussianBlur stdDeviation="1.4"/></filter>
"""
    body = ""
    specs = [  # (y, amp, periods, thickness, colour, opacity, phase)
        (210, 70, 2, 90, "#ffffff", 0.55, 0.0), (300, 60, 1, 60, "#e6f6ff", 0.5, 1.4),
        (420, 90, 2, 120, "#ffffff", 0.45, 2.2), (520, 50, 3, 40, "#dff3ff", 0.55, 0.6),
        (640, 80, 1, 100, "#ffffff", 0.4, 3.1), (740, 60, 2, 50, "#eaf8ff", 0.45, 4.0),
    ]
    for y, amp, per, th, col, op, ph in specs:
        top, bot = [], []
        for xx in range(0, w + 1, 24):
            a = 2 * math.pi * per * xx / w + ph
            c = y + amp * math.sin(a) + amp * 0.35 * math.sin(2 * a + ph)
            t = th * (0.55 + 0.45 * math.sin(a * 0.5 + ph) ** 2)
            top.append((xx, c - t / 2))
            bot.append((xx, c + t / 2))
        d = "M" + " L".join(f"{p[0]} {f(p[1])}" for p in top) + " L" + " L".join(f"{p[0]} {f(p[1])}" for p in reversed(bot)) + "Z"
        body += f'<path d="{d}" fill="{col}" opacity="{op}" filter="url(#fog)"/>'
        line = "M" + " L".join(f"{p[0]} {f(p[1] + 4)}" for p in top)
        body += f'<path d="{line}" fill="none" stroke="#ffffff" stroke-width="3" opacity="{op*0.9:.2f}" filter="url(#fog2)"/>'
        body += f'<path d="{line}" fill="none" stroke="#ffffff" stroke-width="1.2" opacity="{op*0.8:.2f}" filter="url(#fog3)"/>'
    svg("waves.svg", w, h, body, defs)

