def cloud(rnd, cx, cy, w, h):
    """A cumulus: many small billows inside a dome, each lit from the upper
    left and shaded underneath, over a soft blue-grey base."""
    puffs = []
    n = int(w * h / 1700) + 12
    for _ in range(n):
        t = rnd.random()
        env = h * math.sin(math.pi * t) ** 0.75
        r = h * rnd.uniform(0.08, 0.17) * (0.7 + 0.5 * math.sin(math.pi * t))
        y = cy - rnd.uniform(0, max(0.0, env - r)) - r * 0.4
        x = cx - w / 2 + w * t
        puffs.append((x, y, r))
    puffs.sort(key=lambda p: p[1])
    base = (f'<ellipse cx="{f(cx)}" cy="{f(cy - h*0.08)}" rx="{f(w*0.5)}" ry="{f(h*0.14)}" fill="#b6d3ef"/>')
    shade = "".join(f'<circle cx="{f(x+r*0.1)}" cy="{f(y+r*0.22)}" r="{f(r*1.02)}"/>' for x, y, r in puffs)
    lit = "".join(f'<circle cx="{f(x)}" cy="{f(y)}" r="{f(r)}"/>' for x, y, r in puffs)
